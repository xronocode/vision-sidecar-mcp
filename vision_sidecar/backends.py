MLX_MODEL = os.environ.get("MLX_MODEL", "mlx-community/gemma-3-12b-it-4bit")
MLX_MAX_TOKENS = int(os.environ.get("MLX_MAX_TOKENS", "1024"))
MLX_TEMPERATURE = float(os.environ.get("MLX_TEMPERATURE", "0.2"))
MLX_TOP_P = float(os.environ.get("MLX_TOP_P", "0.9"))
MLX_MAX_IMAGE_DIMENSION = int(os.environ.get("MLX_MAX_IMAGE_DIMENSION", "0"))

# -- z.ai cloud vision fallback (OpenAI-compatible) ---------------------------
ZAI_API_KEY = (
    os.environ.get("ZAI_API_KEY")
    or os.environ.get("ZAI_ZAI_API_KEY")
    or os.environ.get("ZHIPUAI_API_KEY")
    or ""
)
ZAI_BASE_URL = os.environ.get("ZAI_BASE_URL", "https://api.z.ai/api/paas/v4").rstrip("/")
ZAI_VISION_MODEL = os.environ.get("ZAI_VISION_MODEL", "glm-4.6v")
ZAI_TIMEOUT = float(os.environ.get("ZAI_TIMEOUT", "120"))
ZAI_MAX_TOKENS = int(os.environ.get("ZAI_MAX_TOKENS", "4096"))
ZAI_TEMPERATURE = float(os.environ.get("ZAI_TEMPERATURE", "0.2"))

# -- GPU contention guard ------------------------------------------------------
# Protects other local ML jobs (whisper/ASR transcriptions, other mlx/llama runs) from being
# starved or OOM-killed by a resident 9.5GB vision model. When the guard detects a competing
# job (or memory pressure, or an advisory lock), it UNLOADS the local model and routes the
# request to the z.ai cloud instead.
GPU_GUARD = os.environ.get("VISION_GPU_GUARD", "1") == "1"
GPU_BUSY_PROCS = [
    p.strip()
    for p in os.environ.get(
        "VISION_GPU_BUSY_PROCS",
        "whisper,mlx-whisper,transcribe.py,llama-server,mlx_lm.server,mlx_lm.server,mlx-vlm",
    ).split(",")
    if p.strip()
]
GPU_LOCK = os.environ.get("VISION_GPU_LOCK", "").strip()
# Skip MLX if system-wide memory free percentage is below this (macOS memory_pressure).
GPU_MIN_FREE_PCT = int(os.environ.get("VISION_GPU_MIN_FREE_PCT", "20"))

VLM_LOG_LEVEL = os.environ.get("VLM_LOG_LEVEL", "WARNING").upper()
_logger = logging.getLogger("vision_sidecar.backends")
if not _logger.handlers:
    _h = logging.StreamHandler()
    _h.setFormatter(logging.Formatter("%(message)s"))
    _logger.addHandler(_h)
_logger.setLevel(getattr(logging, VLM_LOG_LEVEL, logging.WARNING))


def _log(block: str, level: int = logging.INFO, **fields) -> None:
    if not _logger.isEnabledFor(level):
        return
    kv = " ".join(f"{k}={v}" for k, v in fields.items())
    _logger.log(level, f"[VisionSidecar][backends][dispatcher][{block}] {kv}")


# Resident MLX model cache (lazy-loaded on first successful use).
_MLX_CACHE: dict[str, Any] = {"model": None, "processor": None, "config": None}
_MLX_BROKEN = False  # set True if mlx-vlm is missing/uncallable so we stop retrying every call


# START_BLOCK_GPU_GUARD
def _own_pids() -> set[int]:
    """PIDs to ignore when scanning for competing jobs (this process + its parents)."""
    pids = {os.getpid()}
    try:
        p = os.getppid()
        pids.add(p)
    except Exception:
        pass
    return pids


def _pgrep_busy() -> tuple[bool, str]:
    """Detect competing local GPU jobs via pgrep. Never raises."""
    own = _own_pids()
    for pattern in GPU_BUSY_PROCS:
        try:
            res = subprocess.run(
                ["pgrep", "-fil", pattern],
                capture_output=True,
                text=True,
                timeout=4,
            )
        except (FileNotFoundError, subprocess.TimeoutExpired):
            # pgrep missing or slow -> skip process detection entirely.
            return False, ""
        if res.returncode == 0 and res.stdout.strip():
            for line in res.stdout.splitlines():
                parts = line.split(None, 1)
                if parts:
                    try:
                        pid = int(parts[0])
                    except ValueError:
                        continue
                    if pid not in own:
                        return True, f"proc:{pattern}({pid})"
    return False, ""


def _memory_pressure_busy() -> tuple[bool, str]:
    """macOS memory_pressure: busy when free% below GPU_MIN_FREE_PCT. Never raises."""
    try:
        res = subprocess.run(
            ["memory_pressure"], capture_output=True, text=True, timeout=5
        )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return False, ""
    if res.returncode != 0:
        return False, ""
    for line in res.stdout.splitlines():
        low = line.lower()
        if "free percentage" in low:
            digits = "".join(ch for ch in line if ch.isdigit())
            if digits:
                free_pct = int(digits[:3])
                if free_pct < GPU_MIN_FREE_PCT:
                    return True, f"mem_free_{free_pct}%"
                return False, ""
    return False, ""


def _lock_busy() -> tuple[bool, str]:
    if GPU_LOCK and Path(GPU_LOCK).exists():
        return True, "gpu_lock"
    return False, ""


def gpu_busy() -> tuple[bool, str]:
    """Return (busy, reason). A busy GPU means: do NOT run the local MLX model now."""
    if not GPU_GUARD:
        return False, ""
    for check in (_lock_busy, _pgrep_busy, _memory_pressure_busy):
        try:
            busy, reason = check()
        except Exception as e:  # a faulty guard must never block inference
            _log("BLOCK_GPU_GUARD", level=logging.WARNING, check=check.__name__, error=str(e))
            continue
        if busy:
            _log("BLOCK_GPU_GUARD", level=logging.INFO, busy=True, reason=reason)
            return True, reason
    return False, ""


# END_BLOCK_GPU_GUARD


# START_BLOCK_MLX
def _load_mlx() -> None:
    """Lazy-load (and cache) the MLX vision model. Raises on failure."""
    global _MLX_BROKEN
    if _MLX_BROKEN:
        raise RuntimeError("mlx-vlm backend previously failed; disabled for this process")
    if _MLX_CACHE["model"] is not None:
        return
    _log("BLOCK_LOAD_MLX", model=MLX_MODEL)
    import mlx_vlm  # noqa: F401  (lazy: server starts even if mlx_vlm is absent)

    from mlx_vlm import load as vlm_load
    from mlx_vlm.utils import load_config

    t0 = time.perf_counter()
    model, processor = vlm_load(MLX_MODEL)
    config = load_config(MLX_MODEL)
    _MLX_CACHE.update(model=model, processor=processor, config=config)
    _log("BLOCK_LOAD_MLX", phase="exit", wall_seconds=round(time.perf_counter() - t0, 2))
    _tm.event_field(mlx_model=MLX_MODEL, mlx_load_s=round(time.perf_counter() - t0, 2))


def unload_mlx() -> None:
    """Drop the resident MLX model + clear Metal cache so parallel jobs get the memory back."""
    if _MLX_CACHE["model"] is None:
        return
    _log("BLOCK_LOAD_MLX", level=logging.INFO, phase="unload")
    _MLX_CACHE.update(model=None, processor=None, config=None)
    gc.collect()
    try:
        import mlx.core as mx

        clear = getattr(mx, "clear_cache", None) or getattr(mx.metal, "clear_cache", None)
        if clear:
            clear()
    except Exception as e:
        _log("BLOCK_LOAD_MLX", level=logging.WARNING, phase="unload_cache", error=str(e))


def _maybe_resize_for_mlx(image_path: str) -> str:
    """Optionally cap the longest side before MLX (perf/memory). Returns a path (temp if resized)."""
    if MLX_MAX_IMAGE_DIMENSION <= 0:
        return image_path
    try:
        with Image.open(image_path) as im:
            w, h = im.size
            longest = max(w, h)
            if longest <= MLX_MAX_IMAGE_DIMENSION:
                return image_path
            scale = MLX_MAX_IMAGE_DIMENSION / longest
            nw, nh = max(1, int(w * scale)), max(1, int(h * scale))
            resized = im.convert("RGB").resize((nw, nh), Image.Resampling.LANCZOS)
            buf = io.BytesIO()
            resized.save(buf, format="PNG")
            tmp = Path(image_path).with_suffix(".mlxtmp.png")
            tmp.write_bytes(buf.getvalue())
            return str(tmp)
    except Exception as e:
        _log("BLOCK_CALL_MLX", level=logging.WARNING, phase="resize_skip", error=str(e))
        return image_path


def _strip_reasoning(text: str) -> str:
    """Remove <think>...</think> blocks some reasoning VLMs emit before the answer."""
    if not text or "<think>" not in text:
        return text
    import re

    return re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip() or text


def call_mlx(
    image_path: str,
    prompt: str,
    *,
    system_prompt: str,
    max_tokens: int = MLX_MAX_TOKENS,
    temperature: float = MLX_TEMPERATURE,
) -> str:
    """Run the local MLX vision model on one image. Raises on any failure (caller falls back)."""
    from mlx_vlm import apply_chat_template, generate

    _load_mlx()
    model = _MLX_CACHE["model"]
    processor = _MLX_CACHE["processor"]
    config = _MLX_CACHE["config"]

    img_path = _maybe_resize_for_mlx(image_path)
    full_prompt = f"{system_prompt}\n\n{prompt}" if system_prompt else prompt
    formatted = apply_chat_template(processor, config, full_prompt, num_images=1)

    _log("BLOCK_CALL_MLX", phase="entry", model=MLX_MODEL, max_tokens=max_tokens)
    _tm.event_field(mlx_call=1)
    t0 = time.perf_counter()
    try:
        result = generate(
            model,
            processor,
            formatted,
            image=[img_path],
            max_tokens=max_tokens,
            temperature=temperature,
            top_p=MLX_TOP_P,
            verbose=False,
        )
    finally:
        try:
            import mlx.core as mx

            clear = getattr(mx, "clear_cache", None) or getattr(mx.metal, "clear_cache", None)
            if clear:
                clear()
        except Exception:
            pass
    wall = round(time.perf_counter() - t0, 2)
    text = _strip_reasoning(getattr(result, "text", "") or str(result))
    _log("BLOCK_CALL_MLX", phase="exit", wall_seconds=wall, response_chars=len(text), status="ok")
    _tm.event_field(mlx_wall_s=wall, mlx_status="ok", response_chars=len(text))
    return text


# END_BLOCK_MLX


# START_BLOCK_ZAI
def call_zai(
    image_b64: str,
    mime: str,
    prompt: str,
    *,
    system_prompt: str,
    max_tokens: int = ZAI_MAX_TOKENS,
    temperature: float = ZAI_TEMPERATURE,
    response_json: bool = False,
) -> str:
    """Call the z.ai cloud vision API (OpenAI-compatible, plain Bearer auth). Raises on failure."""
    if not ZAI_API_KEY:
        raise RuntimeError("ZAI_API_KEY not set; z.ai fallback unavailable")
    data_url = f"data:{mime};base64,{image_b64}"
    messages: list[dict[str, Any]] = []
    if system_prompt:
        messages.append({"role": "system", "content": system_prompt})
    messages.append(
        {
            "role": "user",
            "content": [
                {"type": "image_url", "image_url": {"url": data_url}},
                {"type": "text", "text": prompt},
            ],
        }
    )
    payload: dict[str, Any] = {
        "model": ZAI_VISION_MODEL,
        "messages": messages,
        "temperature": temperature,
        "max_tokens": max_tokens,
        "stream": False,
    }
    if response_json:
        payload["response_format"] = {"type": "json_object"}
    url = f"{ZAI_BASE_URL}/chat/completions"
    _log("BLOCK_CALL_ZAI", phase="entry", url=url, model=ZAI_VISION_MODEL, response_json=int(response_json))
    _tm.event_field(zai_call=1)
    t0 = time.perf_counter()
    try:
        with httpx.Client(timeout=ZAI_TIMEOUT) as client:
            resp = client.post(url, json=payload, headers={"Authorization": f"Bearer {ZAI_API_KEY}"})
    except httpx.HTTPError as exc:
        _tm.event_field(zai_status="network_error")
        raise RuntimeError(f"z.ai network error: {type(exc).__name__}: {exc}") from exc
    if resp.status_code >= 400:
        # Surface the provider's own error code/message (e.g. 1113 insufficient balance, 1211 unknown model).
        try:
            err = resp.json().get("error", {})
            detail = f"{err.get('code', '?')}: {err.get('message', resp.text[:200])}"
        except Exception:
            detail = resp.text[:200]
        _tm.event_field(zai_status=f"http_{resp.status_code}")
        raise RuntimeError(f"z.ai HTTP {resp.status_code} - {detail}")
    data = resp.json()
    wall = round(time.perf_counter() - t0, 2)
    choices = data.get("choices") or []
    content = ""
    if choices:
        content = choices[0].get("message", {}).get("content", "") or ""
    content = _strip_reasoning(content)
    _log("BLOCK_CALL_ZAI", phase="exit", wall_seconds=wall, response_chars=len(content), status="ok")
    _tm.event_field(zai_wall_s=wall, zai_status="ok", response_chars=len(content))
    return content


# END_BLOCK_ZAI


def _looks_failed(content: str) -> bool:
    """A guard-rail: treat provider error banners as failures so the dispatcher can fall back."""
    if not content:
        return True
    head = content.lstrip()[:40].upper()
    return head.startswith("[VLM_")


def run_vlm(
    *,
    image_path: str,
    image_b64: str,
    mime: str,
    prompt: str,
    system_prompt: str,
    num_predict: int,
    temperature: float,
    response_json: bool = False,
    suppress_thinking: bool = True,
    ollama_fn: Callable[..., str] | None = None,
) -> tuple[str, dict[str, Any]]:
    """Dispatch a vision request across backends and return (content, meta).

    Routing (VLM_BACKEND):
      - auto:  MLX (local) when the GPU is free -> z.ai (cloud) on contention/error.
               On contention the resident MLX model is UNLOADED first so it cannot starve
               the competing job.
      - mlx / zai / ollama: that single backend only (no fallback).
      - mock:  returns a MOCK marker (the tool layer usually short-circuits mock itself).

    meta keys: backend, model, fallback_from, reason.
    """
    backend = VLM_BACKEND
    meta: dict[str, Any] = {"backend": backend, "model": MLX_MODEL}

    if backend == "ollama":
        if ollama_fn is None:
            raise RuntimeError("ollama backend selected but no ollama_fn provided")
        content = ollama_fn(
            image_b64,
            prompt,
            system_prompt=system_prompt,
            temperature=temperature,
            num_predict=num_predict,
            response_json=response_json,
            suppress_thinking=suppress_thinking,
        )
        meta["backend"] = "ollama"
        return content, meta

    if backend == "zai":
        try:
            content = call_zai(
                image_b64, mime, prompt,
                system_prompt=system_prompt,
                max_tokens=min(num_predict or ZAI_MAX_TOKENS, ZAI_MAX_TOKENS) or ZAI_MAX_TOKENS,
                temperature=temperature,
                response_json=response_json,
            )
            meta["model"] = ZAI_VISION_MODEL
            return content, meta
        except Exception as e:
            _log("BLOCK_DISPATCH", level=logging.ERROR, route="zai_failed", error=str(e)[:160])
            return f"[VLM_ERROR] z.ai backend failed: {e}", {**meta, "backend": "error"}

    if backend == "mlx":
        try:
            content = call_mlx(
                image_path, prompt, system_prompt=system_prompt,
                max_tokens=num_predict or MLX_MAX_TOKENS, temperature=temperature,
            )
            meta["backend"] = "mlx"
            return content, meta
        except Exception as e:
            _log("BLOCK_DISPATCH", level=logging.ERROR, route="mlx_failed", error=str(e)[:160])
            return f"[VLM_ERROR] mlx backend failed: {e}", {**meta, "backend": "error"}

    # ---- auto: local MLX first, z.ai fallback, with a GPU-contention guard ----
    busy, reason = gpu_busy()
    if busy:
        if not VLM_ALLOW_CLOUD:
            _log("BLOCK_DISPATCH", level=logging.WARNING, route="mlx_busy", reason=reason, cloud="blocked")
            return (
                f"[VLM_ERROR] Local GPU is busy ({reason}) and cloud fallback is disabled. "
                "Free the GPU, or set VLM_ALLOW_CLOUD=1 to permit the z.ai fallback.",
                {**meta, "backend": "error"},
            )
        _log("BLOCK_DISPATCH", level=logging.INFO, route="mlx->zai", reason=reason)
        unload_mlx()
        content = call_zai(
            image_b64, mime, prompt,
            system_prompt=system_prompt,
            max_tokens=min(num_predict or ZAI_MAX_TOKENS, ZAI_MAX_TOKENS) or ZAI_MAX_TOKENS,
            temperature=temperature,
            response_json=response_json,
        )
        meta.update(backend="zai", model=ZAI_VISION_MODEL, fallback_from="mlx", reason=reason)
        return content, meta

    try:
        content = call_mlx(
            image_path, prompt, system_prompt=system_prompt,
            max_tokens=num_predict or MLX_MAX_TOKENS, temperature=temperature,
        )
        if not _looks_failed(content):
            meta["backend"] = "mlx"
            return content, meta
        raise RuntimeError("mlx returned empty/error content")
    except Exception as e:
        global _MLX_BROKEN
        # mlx-vlm import/install failures are permanent for this process.
        if isinstance(e, (ImportError, ModuleNotFoundError)):
            _MLX_BROKEN = True
        _log("BLOCK_DISPATCH", level=logging.WARNING, route="mlx_failed->zai", error=str(e)[:160])
        unload_mlx()
        if not VLM_ALLOW_CLOUD:
            return (
                f"[VLM_ERROR] Local MLX failed ({type(e).__name__}: {str(e)[:120]}) "
                "and cloud fallback is disabled. Set VLM_ALLOW_CLOUD=1 to permit "
                "the z.ai fallback.",
                {**meta, "backend": "error"},
            )
        try:
            content = call_zai(
                image_b64, mime, prompt,
                system_prompt=system_prompt,
                max_tokens=min(num_predict or ZAI_MAX_TOKENS, ZAI_MAX_TOKENS) or ZAI_MAX_TOKENS,
                temperature=temperature,
                response_json=response_json,
            )
            meta.update(backend="zai", model=ZAI_VISION_MODEL, fallback_from="mlx", reason=f"mlx_error:{type(e).__name__}")
            return content, meta
        except Exception as e2:
            _log("BLOCK_DISPATCH", level=logging.ERROR, route="zai_failed", error=str(e2)[:160])
            _tm.event_field(zai_status="error")
            return (
                f"[VLM_ERROR] Local MLX failed ({type(e).__name__}: {str(e)[:120]}) "
                f"and z.ai fallback failed ({type(e2).__name__}: {str(e2)[:120]}).",
                {**meta, "backend": "error"},
            )


def backend_status() -> dict[str, Any]:
    """Snapshot of backend availability for check_vlm_status()."""
    import importlib.util as _ilu

    mlx_vlm_present = _ilu.find_spec("mlx_vlm") is not None
    busy, reason = gpu_busy()
    return {
        "vlm_backend": VLM_BACKEND,
        "mlx": {
            "model": MLX_MODEL,
            "package_available": mlx_vlm_present,
            "loaded": _MLX_CACHE["model"] is not None,
            "permanently_disabled": _MLX_BROKEN,
        },
        "zai": {
            "base_url": ZAI_BASE_URL,
            "vision_model": ZAI_VISION_MODEL,
            "api_key_set": bool(ZAI_API_KEY),
        },
        "gpu_guard": {"enabled": GPU_GUARD, "busy": busy, "reason": reason,
                      "busy_procs": GPU_BUSY_PROCS, "min_free_pct": GPU_MIN_FREE_PCT},
    }
